/** What an installed product ships, read from its files: jars inside jars, installed npm and Python packages. */
class InstalledReadersTest {

    @TempDir
    Path root;

    /** A jar of these entries, a name and its content each (bytes, a String, or a nested jar's bytes). */
    static byte[] jar(Object... nameAndContent) throws IOException {
        var bytes = new ByteArrayOutputStream();
        try (var zip = new ZipOutputStream(bytes)) {
            for (int i = 0; i < nameAndContent.length; i += 2) {
                zip.putNextEntry(new ZipEntry((String) nameAndContent[i]));
                Object c = nameAndContent[i + 1];
                zip.write(c instanceof byte[] b ? b : c.toString().getBytes(StandardCharsets.UTF_8));
                zip.closeEntry();
            }
        }
        return bytes.toByteArray();
    }

    static String pom(String g, String a, String v) {
        return "#Generated by Maven\ngroupId=" + g + "\nartifactId=" + a + "\nversion=" + v + "\n";
    }

    private List<String> read(List<Path> jars) {
        var col = new DependencyCollector(root);
        var warnings = new ArrayList<Phrase>();
        JarReader.scan(jars, col, warnings::add);
        var found = new TreeSet<String>();
        col.deps.forEach(d -> found.add(d.name() + " " + d.version() + " " + d.file() + " " + d.scope() + (d.bundle() == null ? "" : " " + d.bundle())));
        col.unresolved.forEach(u -> found.add("unchecked " + u.name() + " " + u.declared() + " " + u.file()));
        warnings.forEach(w -> found.add("warning " + w.key()));
        return List.copyOf(found);
    }

    @Test
    void aFatJarsWarsAndEarsJarsAreReadWithoutExtractingThem() throws IOException {
        byte[] log4j = jar("META-INF/maven/org.apache.logging.log4j/log4j-core/pom.properties", pom("org.apache.logging.log4j", "log4j-core", "2.14.1"));
        byte[] plain = jar("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nImplementation-Title: plain-lib\nImplementation-Version: 1.0\n", "a/B.class", "x");
        Path app = Files.write(root.resolve("app.jar"), jar("META-INF/maven/com.example/app/pom.properties", pom("com.example", "app", "1.0"),
                "BOOT-INF/lib/broken-1.0.jar", "not a jar inside", "BOOT-INF/lib/log4j-core-2.14.1.jar", log4j, "BOOT-INF/lib/plain-1.0.jar", plain));
        byte[] text = jar("META-INF/maven/org.apache.commons/commons-text/pom.properties", pom("org.apache.commons", "commons-text", "1.9"));
        byte[] war = jar("WEB-INF/lib/commons-text-1.9.jar", text);
        Path ear = Files.write(root.resolve("shop.ear"), jar("shop.war", war));
        byte[] shaded = jar("META-INF/maven/a/one/pom.properties", pom("a", "one", "1"), "META-INF/maven/b/two/pom.properties", pom("b", "two", "2"));
        Path shadedJar = Files.write(root.resolve("shaded.jar"), shaded);
        Path broken = Files.write(root.resolve("broken.jar"), "not a zip at all".getBytes(StandardCharsets.UTF_8));
        assertEquals(List.of(
                "a:one 1 shaded.jar installed", "b:two 2 shaded.jar installed",
                "com.example:app 1.0 app.jar installed",
                "org.apache.commons:commons-text 1.9 shop.ear!/shop.war!/WEB-INF/lib/commons-text-1.9.jar installed",
                "org.apache.logging.log4j:log4j-core 2.14.1 app.jar!/BOOT-INF/lib/log4j-core-2.14.1.jar installed",
                "plain 1.0 app.jar!/BOOT-INF/lib/plain-1.0.jar installed"),
                read(List.of(app, ear, shadedJar, broken)).stream().filter(s -> !s.startsWith("warning")).toList());
        assertEquals(List.of("warning warning.skipped"), read(List.of(broken)), "not a zip: said, nothing claimed");
        assertTrue(read(List.of(app)).contains("warning warning.skipped"), "a broken jar inside is said, and the jars after it still read");
    }

    @Test
    void aJarWithoutCoordinatesIsCheckedByItsNameItsOsgiNameKept() throws IOException {
        Path text = Files.write(root.resolve("commons-text-1.9.jar"),
                jar("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nBundle-SymbolicName: org.apache.commons.commons-text;singleton:=true\n"));
        Path log4j = Files.write(root.resolve("log4j-core-2.14.1.jar"),
                jar("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nBundle-SymbolicName: org.apache.logging.log4j.core\n"));
        Path versionless = Files.write(root.resolve("tools.jar"),
                jar("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nImplementation-Title: Tools\n"));
        Path byManifest = Files.write(root.resolve("helper.jar"),
                jar("META-INF/MANIFEST.MF", "Manifest-Version: 1.0\nImplementation-Title: helper\nImplementation-Version: 3.1\n"));
        assertEquals(List.of("commons-text 1.9 commons-text-1.9.jar installed org.apache.commons.commons-text",
                "log4j-core 2.14.1 log4j-core-2.14.1.jar installed org.apache.logging.log4j.core",
                "unchecked Tools  tools.jar",
                "unchecked helper 3.1 helper.jar"), read(List.of(text, log4j, versionless, byManifest)),
                "no artifactId in its file name, or no version: not checked");
    }

    @Test
    void anAdvisoryIsAJarsOwnWhenItsOsgiNameIsOfTheAdvisorysGroupANameMatchOtherwise() {
        var guava = new Dependency(Ecosystem.MAVEN, "guava", "31.1-jre", "guava-31.1-jre.jar", "installed", false, "com.google.guava");
        assertTrue(guava.bundleOf("com.google.guava"), "the group itself");
        assertFalse(guava.bundleOf("com.google.guava.testing"), "a group below it is another's");
        var log4j = new Dependency(Ecosystem.MAVEN, "log4j-core", "2.14.1", "x.jar", "installed", false, "org.apache.logging.log4j.core");
        assertTrue(log4j.bundleOf("org.apache.logging.log4j"), "under the group");
        var collections = new Dependency(Ecosystem.MAVEN, "commons-collections", "3.2.1", "x.jar", "installed", false, "org.apache.commons.collections");
        assertFalse(collections.bundleOf("commons-collections"), "another group: a name match, to check");
        assertFalse(new Dependency(Ecosystem.MAVEN, "a", "1", "x.jar", "installed", false).bundleOf("g"));
    }

    @Test
    void anInstalledScanFindsWhatAProductShipsInEveryFolder() throws IOException {
        Files.createDirectories(root.resolve("dist/lib"));
        Files.write(root.resolve("dist/lib/app.jar"), jar("META-INF/maven/g/a/pom.properties", pom("g", "a", "1")));
        Files.createDirectories(root.resolve("app/node_modules/@scope/pkg/node_modules/minimist"));
        Files.writeString(root.resolve("app/package.json"), "{\"name\":\"app\",\"version\":\"1.0.0\"}");
        Files.writeString(root.resolve("app/node_modules/@scope/pkg/package.json"), "{\"name\":\"@scope/pkg\",\"version\":\"2.0.0\"}");
        Files.writeString(root.resolve("app/node_modules/@scope/pkg/node_modules/minimist/package.json"), "{\"name\":\"minimist\",\"version\":\"1.2.5\"}");
        Files.createDirectories(root.resolve(".venv/lib/python3.11/site-packages/Requests-2.25.0.dist-info"));
        Files.createDirectories(root.resolve(".git/objects"));
        Files.writeString(root.resolve(".git/objects/x.jar"), "not read");
        Files.writeString(root.resolve(".venv/lib/python3.11/site-packages/Requests-2.25.0.dist-info/METADATA"),
                "Metadata-Version: 2.1\nName: Requests\nVersion: 2.25.0\n\nName: not this\n");
        Files.writeString(root.resolve("app/pom.xml"), "<project/>");
        var files = ProjectFiles.find(root, ScanMode.INSTALLED);
        assertEquals(1, files.jars.size(), "the product's jar, not one under .git");
        assertEquals(1, files.pythonMetadata.size(), "a .venv is read: it is where an installation keeps its packages");
        assertEquals(2, files.installedPackageJsons.size(), "the installed packages, not the application's own package.json");
        assertTrue(files.poms.isEmpty() && files.packageJsons.isEmpty(), "no source manifest in an installed scan");
        var col = new DependencyCollector(root);
        InstalledNpmReader.scan(files.installedPackageJsons, col, w -> { throw new AssertionError(w); });
        PythonReader.scan(files.pythonMetadata, col, w -> { throw new AssertionError(w); });
        var found = new TreeSet<String>();
        col.deps.forEach(d -> found.add(d.ecosystem() + " " + d.name() + " " + d.version() + " " + d.scope()));
        assertEquals(List.of("PyPI Requests 2.25.0 installed", "npm @scope/pkg 2.0.0 installed", "npm minimist 1.2.5 installed"), List.copyOf(found));
        assertTrue(ProjectFiles.find(root, ScanMode.SOURCES).jars.isEmpty(), "a sources scan reads no jar");
    }
}
