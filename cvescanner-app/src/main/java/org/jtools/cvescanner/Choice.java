import org.jtools.cvescanner.i18n.I18n;

/** A choice of a drop list, shown in the language in use; known by its key, never by the text it shows. */
record Choice<T>(String key, T value) {
    @Override
    public String toString() {
        return I18n.text(key);
    }
}
